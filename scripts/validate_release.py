"""Validate generated release metadata before pushing or publishing.

Maintainer tooling runs on Python 3.12, independently of runtime Python support.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import re
import subprocess
import tomllib


def _git(*arguments: str) -> str:
    """Read Git state without invoking a shell."""
    return subprocess.check_output(  # noqa: S603 -- Fixed Git command.
        ["git", *arguments],  # noqa: S607 -- Required maintainer tool.
        text=True,
    ).strip()


def validate(mode: str, tag: str) -> None:
    """Reject tags without an isolated, generated release commit.

    Args:
        mode: ``prepared`` before an atomic push, or ``tag`` before publishing.
        tag: Complete final semantic version with a leading ``v``.

    Raises:
        ValueError: The candidate violates the release contract.
    """
    if not re.fullmatch(r"v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)", tag):
        raise ValueError("Release tag must be vMAJOR.MINOR.PATCH.")
    version = tag[1:]
    metadata = tomllib.loads(pathlib.Path("pyproject.toml").read_text())
    if metadata["project"]["version"] != version:
        raise ValueError("Release tag must match the package version.")
    if _git("show", "-s", "--format=%s", "HEAD") != (
        f"chore(release): {version}"
    ):
        raise ValueError("Release commit must be generated by release tooling.")
    files = set(
        _git(
            "diff-tree", "--no-commit-id", "--name-only", "-r", "HEAD"
        ).splitlines()
    )
    if "CHANGELOG.md" not in files or files - {
        "CHANGELOG.md",
        "pyproject.toml",
    }:
        raise ValueError(
            "Release commit may only update version and changelog."
        )
    previous = tomllib.loads(_git("show", "HEAD^:pyproject.toml"))
    previous["project"]["version"] = version
    if previous != metadata:
        raise ValueError("Release metadata may only change project.version.")
    changelog = pathlib.Path("CHANGELOG.md").read_text()
    if not re.search(rf"^## v{re.escape(version)}\s", changelog, re.MULTILINE):
        raise ValueError("Release requires a generated changelog entry.")
    if _git("status", "--porcelain"):
        raise ValueError("Release requires a clean checkout.")
    if mode == "prepared":
        if _git("rev-parse", "HEAD^") != _git("rev-parse", "origin/main"):
            raise ValueError("Release must be prepared from current main.")
    else:
        if os.environ.get("GITHUB_ACTOR") != "coval-release-automation[bot]":
            raise ValueError("Release tag must be pushed by the release App.")
        subprocess.run(
            ["git", "merge-base", "--is-ancestor", "HEAD", "origin/main"],  # noqa: S607 -- Fixed Git command.
            check=True,
        )


def main() -> None:
    """Validate one candidate using the current repository checkout."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("prepared", "tag"))
    parser.add_argument("tag")
    arguments = parser.parse_args()
    validate(arguments.mode, arguments.tag)


if __name__ == "__main__":
    main()
